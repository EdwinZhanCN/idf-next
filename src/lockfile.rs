//! `idf.lock`: pins everything a build depends on that `idf.toml` leaves open
//! (invariant 7). It is independent of the idf-next version; upgrading any
//! entry is an explicit action.
//!
//! ```toml
//! version = 1
//!
//! [idf]
//! version = "6.0.1"
//! commit = "<40 hex>"
//!
//! [python]
//! version = "3.12.11"
//! requirements = "sha256:<64 hex>"
//!
//! [[tool]]
//! name = "xtensa-esp-elf"
//! version = "esp-15.1.0_20250911"
//! [tool.archives.macos-arm64]
//! url = "https://…"
//! sha256 = "<64 hex>"
//! size = 123
//!
//! [[component]]
//! name = "espressif/led_strip"
//! version = "3.0.1"
//! source = "registry+https://components.espressif.com"
//! hash = "sha256:<64 hex>"
//! ```

use crate::diagnostic::{self, FileError, Source};
use crate::idf_support;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::fmt;
use std::path::Path;
use std::str::FromStr;

pub const FILE_NAME: &str = "idf.lock";

/// Bumped only when the format changes incompatibly.
pub const FORMAT_VERSION: u32 = 1;

const HEADER: &str = "# This file is generated by idf. Do not edit it by hand.\n\n";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Lockfile {
    pub version: u32,
    pub idf: LockedIdf,
    pub python: LockedPython,
    #[serde(default, rename = "tool", skip_serializing_if = "Vec::is_empty")]
    pub tools: Vec<LockedTool>,
    #[serde(default, rename = "component", skip_serializing_if = "Vec::is_empty")]
    pub components: Vec<LockedComponent>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedIdf {
    pub version: semver::Version,
    /// Full commit hash of the ESP-IDF checkout.
    pub commit: CommitHash,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedPython {
    /// Interpreter version uv installs for the SDK venv.
    pub version: semver::Version,
    /// Hash of the fully resolved requirement set the venv was built from.
    pub requirements: Digest,
}

/// One toolchain package from the SDK's `tools.json`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedTool {
    pub name: String,
    pub version: String,
    /// Host platform (e.g. `macos-arm64`, `linux-amd64`) → archive.
    pub archives: BTreeMap<String, Archive>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Archive {
    pub url: String,
    /// Hex SHA-256 of the archive, as `tools.json` records it.
    pub sha256: Sha256Hex,
    pub size: u64,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LockedComponent {
    pub name: String,
    pub version: String,
    pub source: ComponentSource,
    /// Content hash of the component as downloaded. Absent for `path` sources.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub hash: Option<Digest>,
}

// ------------------------------------------------------------ value types ---

macro_rules! string_newtype {
    ($name:ident, $check:expr) => {
        #[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]
        #[serde(transparent)]
        pub struct $name(String);

        impl $name {
            pub fn as_str(&self) -> &str {
                &self.0
            }
        }

        impl FromStr for $name {
            type Err = String;
            fn from_str(s: &str) -> Result<Self, String> {
                let check: fn(&str) -> Result<(), String> = $check;
                check(s).map(|()| $name(s.to_owned()))
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(&self.0)
            }
        }

        impl<'de> Deserialize<'de> for $name {
            fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
                String::deserialize(d)?
                    .parse()
                    .map_err(serde::de::Error::custom)
            }
        }
    };
}

fn is_lower_hex(s: &str, len: usize) -> bool {
    s.len() == len && s.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f'))
}

string_newtype!(CommitHash, |s| {
    if is_lower_hex(s, 40) {
        Ok(())
    } else {
        Err(format!("{s:?} is not a full 40-character commit hash"))
    }
});

string_newtype!(Sha256Hex, |s| {
    if is_lower_hex(s, 64) {
        Ok(())
    } else {
        Err(format!("{s:?} is not a lowercase hex SHA-256"))
    }
});

string_newtype!(Digest, |s| {
    match s.strip_prefix("sha256:") {
        Some(hex) if is_lower_hex(hex, 64) => Ok(()),
        _ => Err(format!(
            "{s:?} is not a digest; expected \"sha256:<64 hex>\""
        )),
    }
});

/// Where a component came from, Cargo.lock style:
/// `registry+<url>`, `git+<url>#<commit>`, or `path+<relative path>`.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub enum ComponentSource {
    Registry { url: String },
    Git { url: String, commit: CommitHash },
    Path { path: String },
}

impl FromStr for ComponentSource {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, String> {
        let bad =
            || format!("{s:?} is not a source; expected registry+URL, git+URL#COMMIT or path+PATH");
        let (kind, rest) = s.split_once('+').ok_or_else(bad)?;
        if rest.is_empty() {
            return Err(bad());
        }
        match kind {
            "registry" => Ok(Self::Registry {
                url: rest.to_owned(),
            }),
            "path" => Ok(Self::Path {
                path: rest.to_owned(),
            }),
            "git" => {
                let (url, commit) = rest.rsplit_once('#').ok_or_else(bad)?;
                if url.is_empty() {
                    return Err(bad());
                }
                Ok(Self::Git {
                    url: url.to_owned(),
                    commit: commit.parse()?,
                })
            }
            _ => Err(bad()),
        }
    }
}

impl fmt::Display for ComponentSource {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Registry { url } => write!(f, "registry+{url}"),
            Self::Git { url, commit } => write!(f, "git+{url}#{commit}"),
            Self::Path { path } => write!(f, "path+{path}"),
        }
    }
}

impl Serialize for ComponentSource {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.collect_str(self)
    }
}

impl<'de> Deserialize<'de> for ComponentSource {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        String::deserialize(d)?
            .parse()
            .map_err(serde::de::Error::custom)
    }
}

// ------------------------------------------------------------ read/write ---

impl Lockfile {
    pub fn load(path: &Path) -> Result<Self, FileError> {
        let text = diagnostic::read(path)?;
        Self::parse(&text, &path.display().to_string())
    }

    pub fn parse(text: &str, name: &str) -> Result<Self, FileError> {
        let src = Source { name, text };

        // Check the format version first, so a newer lock file gets a clear
        // message instead of an "unknown field" error.
        #[derive(Deserialize)]
        struct Probe {
            version: Option<toml::Spanned<i64>>,
        }
        let probe: Probe = toml::from_str(text).map_err(|e| src.toml_error(e))?;
        match probe.version {
            None => return Err(src.error("idf.lock has no `version`", None, "")),
            Some(v) if *v.get_ref() != i64::from(FORMAT_VERSION) => {
                return Err(src
                    .error(
                        format!("unsupported idf.lock format version {}", v.get_ref()),
                        Some(v.span()),
                        format!("this idf reads version {FORMAT_VERSION}"),
                    )
                    .with_help(
                        "the lock file was written by a different idf-next; use a matching version",
                    ));
            }
            Some(_) => {}
        }

        let lock: Lockfile = toml::from_str(text).map_err(|e| src.toml_error(e))?;
        if !idf_support::supports(&lock.idf.version) {
            return Err(src
                .error(
                    format!(
                        "idf.lock pins ESP-IDF {}, which this idf-next does not support",
                        lock.idf.version
                    ),
                    None,
                    "",
                )
                .with_help(format!(
                    "idf-next {} supports ESP-IDF {}",
                    env!("CARGO_PKG_VERSION"),
                    idf_support::SUPPORTED_IDF_RANGE
                )));
        }
        Ok(lock)
    }

    /// Serialize deterministically: entries sorted, fixed header.
    pub fn to_toml_string(&self) -> String {
        let mut lock = self.clone();
        lock.tools.sort_by(|a, b| a.name.cmp(&b.name));
        lock.components
            .sort_by(|a, b| a.name.cmp(&b.name).then_with(|| a.source.cmp(&b.source)));
        let body = toml::to_string_pretty(&lock).expect("lock file is always serializable");
        format!("{HEADER}{body}")
    }

    /// Write atomically (temp file + rename) so an interrupted write never
    /// leaves a truncated lock behind.
    pub fn save(&self, path: &Path) -> std::io::Result<()> {
        let tmp = path.with_extension("lock.tmp");
        std::fs::write(&tmp, self.to_toml_string())?;
        std::fs::rename(&tmp, path)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> Lockfile {
        let hex64 = "ab".repeat(32);
        Lockfile {
            version: FORMAT_VERSION,
            idf: LockedIdf {
                version: semver::Version::new(6, 0, 1),
                commit: "0123456789abcdef0123456789abcdef01234567".parse().unwrap(),
            },
            python: LockedPython {
                version: semver::Version::new(3, 12, 11),
                requirements: format!("sha256:{hex64}").parse().unwrap(),
            },
            tools: vec![
                LockedTool {
                    name: "xtensa-esp-elf".into(),
                    version: "esp-15.1.0_20250911".into(),
                    archives: BTreeMap::from([(
                        "macos-arm64".into(),
                        Archive {
                            url: "https://example.com/x.tar.xz".into(),
                            sha256: hex64.parse().unwrap(),
                            size: 42,
                        },
                    )]),
                },
                LockedTool {
                    name: "cmake".into(),
                    version: "3.30.2".into(),
                    archives: BTreeMap::new(),
                },
            ],
            components: vec![
                LockedComponent {
                    name: "local".into(),
                    version: "0.1.0".into(),
                    source: "path+components/local".parse().unwrap(),
                    hash: None,
                },
                LockedComponent {
                    name: "espressif/led_strip".into(),
                    version: "3.0.1".into(),
                    source: "registry+https://components.espressif.com".parse().unwrap(),
                    hash: Some(format!("sha256:{hex64}").parse().unwrap()),
                },
            ],
        }
    }

    #[test]
    fn round_trips_and_sorts() {
        let lock = sample();
        let text = lock.to_toml_string();
        assert!(text.starts_with(HEADER));
        let back = Lockfile::parse(&text, "idf.lock").unwrap();
        assert_eq!(back.tools[0].name, "cmake");
        assert_eq!(back.components[0].name, "espressif/led_strip");
        // Serializing again is byte-for-byte stable.
        assert_eq!(back.to_toml_string(), text);
        insta::assert_snapshot!(text);
    }

    #[test]
    fn rejects_other_format_versions() {
        let text = sample()
            .to_toml_string()
            .replace("version = 1\n", "version = 2\n");
        let err = Lockfile::parse(&text, "idf.lock").unwrap_err();
        assert!(
            err.to_string()
                .contains("unsupported idf.lock format version 2"),
            "{err}"
        );
    }

    #[test]
    fn rejects_bad_values() {
        let text = sample()
            .to_toml_string()
            .replace("0123456789abcdef0123456789abcdef01234567", "abc123");
        let err = Lockfile::parse(&text, "idf.lock").unwrap_err();
        let label = &err.invalid().unwrap().label;
        assert!(label.contains("40-character commit hash"), "{label}");

        let text = sample()
            .to_toml_string()
            .replace("version = \"6.0.1\"", "version = \"5.4.0\"");
        let err = Lockfile::parse(&text, "idf.lock").unwrap_err();
        assert!(err.to_string().contains("does not support"), "{err}");
    }

    #[test]
    fn component_sources() {
        let git: ComponentSource = "git+https://x/y.git#0123456789abcdef0123456789abcdef01234567"
            .parse()
            .unwrap();
        assert_eq!(
            git.to_string(),
            "git+https://x/y.git#0123456789abcdef0123456789abcdef01234567"
        );
        assert!("git+https://x/y.git".parse::<ComponentSource>().is_err());
        assert!("ftp+x".parse::<ComponentSource>().is_err());
        assert!("registry+".parse::<ComponentSource>().is_err());
    }
}
