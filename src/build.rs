//! Turning `idf.toml` into a CMake project under `build/`, and driving
//! CMake and Ninja on it.
//!
//! Everything generated lives in `build/<target>/<profile>/`:
//!
//! ```text
//! project/CMakeLists.txt       include IDF's project.cmake; SDKCONFIG paths
//! project/main/CMakeLists.txt  the `main` component: every source in src/
//! project/sdkconfig.defaults   [config] (+ profile) and the partition table
//! project/partitions.csv       [[partition]], when given
//! sdkconfig, build.ninja, …    CMake's binary dir is the profile dir itself
//! ```
//!
//! IDF's CMake framework runs unmodified. Generated files are rewritten only
//! when their content changes, so Ninja's own dependency tracking decides
//! what to rebuild.

use crate::chip::Chip;
use crate::fsx;
use crate::manifest::{ConfigKey, ConfigValue, Manifest, Partition};
use crate::project::Project;
use crate::sdk::{Environment, Installed};
use crate::ui;
use miette::{IntoDiagnostic, Result, WrapErr, bail};
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

const HEADER: &str = "Generated by idf from idf.toml. Do not edit.";

/// Kconfig files `src/` may hold, as a component directory would.
const KCONFIG_FILES: &[&str] = &["Kconfig", "Kconfig.projbuild"];

/// Source files that go into the `main` component.
const SOURCE_EXTENSIONS: &[&str] = &["c", "cc", "cpp", "cxx", "S", "s"];

/// Where one (target, profile) build lives.
#[derive(Debug, Clone)]
pub struct Layout {
    pub root: PathBuf,
    pub target: Chip,
    pub profile: String,
}

impl Layout {
    pub fn new(root: &Path, target: &Chip, profile: &str) -> Layout {
        Layout {
            root: root.to_owned(),
            target: target.clone(),
            profile: profile.to_owned(),
        }
    }

    /// `build/` in the project.
    pub fn build_root(&self) -> PathBuf {
        self.root.join("build")
    }

    /// CMake's binary directory, `build/<target>/<profile>`.
    pub fn dir(&self) -> PathBuf {
        self.build_root()
            .join(self.target.as_str())
            .join(&self.profile)
    }

    /// The generated CMake source directory.
    pub fn project_dir(&self) -> PathBuf {
        self.dir().join("project")
    }

    pub fn sdkconfig(&self) -> PathBuf {
        self.dir().join("sdkconfig")
    }

    fn relative_dir(&self) -> PathBuf {
        Path::new("build")
            .join(self.target.as_str())
            .join(&self.profile)
    }
}

/// What [`generate`] changed.
#[derive(Debug, Default)]
pub struct Generated {
    /// Any generated file was written.
    pub changed: bool,
    /// Only `sdkconfig.defaults` and the partition table changed: the
    /// component set and Kconfig files are as the last configure saw them.
    pub only_values: bool,
}

/// Write the CMake project for `layout`.
pub fn generate(project: &Project, layout: &Layout) -> Result<Generated> {
    let m = &project.manifest;
    let src = layout.root.join("src");
    let sources = sources(&src)?;
    if sources.is_empty() {
        bail!(
            help = "Add at least one .c or .cpp file with `void app_main(void)`.",
            "no source files in {}",
            src.display()
        );
    }
    let components = layout.root.join("components");
    let components = components.is_dir().then_some(components);

    let pdir = layout.project_dir();
    let deps_changed = crate::deps::sync_files(m, project.lock.as_ref(), layout)?;
    let mut g = Generated {
        changed: deps_changed,
        ..Generated::default()
    };
    let mut removed = false;
    let mut structure = deps_changed;
    let mut put = |path: PathBuf, text: String, values: bool| -> Result<bool> {
        let wrote = write_if_changed(&path, &text)?;
        g.changed |= wrote;
        structure |= wrote && !values;
        Ok(wrote)
    };
    put(
        pdir.join("CMakeLists.txt"),
        top_cmakelists(
            m.project.name.get_ref(),
            &layout.sdkconfig(),
            components.as_deref(),
        ),
        false,
    )?;
    put(
        pdir.join("main/CMakeLists.txt"),
        main_cmakelists(&sources, &src),
        false,
    )?;
    // Kconfig menus for the project's own options. IDF only reads them from
    // the component directory, so a stub there sources the real file; that
    // keeps `rsource` inside it relative to src/.
    for name in KCONFIG_FILES {
        let (from, to) = (src.join(name), pdir.join("main").join(name));
        if from.is_file() {
            put(
                to,
                kconfig_stub(&std::path::absolute(&from).into_diagnostic()?),
                false,
            )?;
        } else if to.exists() {
            std::fs::remove_file(&to)
                .into_diagnostic()
                .wrap_err_with(|| format!("removing {}", to.display()))?;
            removed = true;
        }
    }
    let has_table = !m.partitions.is_empty();
    if has_table {
        put(
            pdir.join("partitions.csv"),
            partitions_csv(&m.partitions),
            true,
        )?;
    }
    let defaults = defaults_text(m, &layout.profile);
    let defaults_changed = put(pdir.join("sdkconfig.defaults"), defaults, true)?;
    g.changed |= removed;
    g.only_values = g.changed && !structure && !removed;
    if defaults_changed {
        // IDF applies defaults only to symbols missing from sdkconfig. idf.toml
        // is the single source of truth, so start sdkconfig over from them.
        let sdkconfig = layout.sdkconfig();
        if sdkconfig.exists() {
            std::fs::remove_file(&sdkconfig)
                .into_diagnostic()
                .wrap_err_with(|| format!("removing {}", sdkconfig.display()))?;
        }
    }
    Ok(g)
}

/// All source files under `src/`, sorted, as absolute paths.
fn sources(src: &Path) -> Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    let mut stack = vec![src.to_owned()];
    while let Some(dir) = stack.pop() {
        let entries = match std::fs::read_dir(&dir) {
            Ok(e) => e,
            Err(e) if e.kind() == std::io::ErrorKind::NotFound && dir == src => break,
            Err(e) => {
                return Err(e)
                    .into_diagnostic()
                    .wrap_err_with(|| format!("reading {}", dir.display()));
            }
        };
        for entry in entries {
            let path = entry.into_diagnostic()?.path();
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if name.starts_with('.') {
                continue;
            }
            if path.is_dir() {
                stack.push(path);
            } else if path
                .extension()
                .and_then(|e| e.to_str())
                .is_some_and(|e| SOURCE_EXTENSIONS.contains(&e))
            {
                out.push(std::path::absolute(&path).into_diagnostic()?);
            }
        }
    }
    out.sort();
    Ok(out)
}

/// A CMake bracket argument, so paths never need escaping.
fn cmake_str(s: &str) -> String {
    let mut eq = String::from("=");
    while s.contains(&format!("]{eq}]")) {
        eq.push('=');
    }
    format!("[{eq}[{s}]{eq}]")
}

fn cmake_path(p: &Path) -> String {
    cmake_str(&p.to_string_lossy())
}

fn top_cmakelists(name: &str, sdkconfig: &Path, components: Option<&Path>) -> String {
    let mut s = format!("# {HEADER}\ncmake_minimum_required(VERSION 3.22)\n\n");
    let _ = writeln!(s, "set(SDKCONFIG {})", cmake_path(sdkconfig));
    s.push_str("set(SDKCONFIG_DEFAULTS \"${CMAKE_CURRENT_LIST_DIR}/sdkconfig.defaults\")\n");
    if let Some(dir) = components {
        let _ = writeln!(s, "set(EXTRA_COMPONENT_DIRS {})", cmake_path(dir));
    }
    s.push_str("\ninclude($ENV{IDF_PATH}/tools/cmake/project.cmake)\n");
    let _ = writeln!(s, "project({name})");
    s
}

fn main_cmakelists(sources: &[PathBuf], include: &Path) -> String {
    let mut s = format!("# {HEADER}\nidf_component_register(\n    SRCS\n");
    for src in sources {
        let _ = writeln!(s, "        {}", cmake_path(src));
    }
    let _ = writeln!(s, "    INCLUDE_DIRS\n        {}\n)", cmake_path(include));
    s
}

fn kconfig_stub(real: &Path) -> String {
    let path = real
        .to_string_lossy()
        .replace('\\', "\\\\")
        .replace('"', "\\\"");
    format!("# {HEADER}\nsource \"{path}\"\n")
}

fn kconfig_line(key: &ConfigKey, value: &ConfigValue) -> String {
    match value {
        ConfigValue::Bool(true) => format!("CONFIG_{key}=y"),
        ConfigValue::Bool(false) => format!("# CONFIG_{key} is not set"),
        ConfigValue::Int(n) => format!("CONFIG_{key}={n}"),
        // Kconfig reads a `hex` symbol's digits as hex even without `0x`, so
        // an integer cannot carry a hex value; it is written as "0x…" instead.
        ConfigValue::String(v) if is_hex_literal(v) => format!("CONFIG_{key}={v}"),
        ConfigValue::String(v) => {
            let escaped = v.replace('\\', "\\\\").replace('"', "\\\"");
            format!("CONFIG_{key}=\"{escaped}\"")
        }
    }
}

fn is_hex_literal(s: &str) -> bool {
    s.strip_prefix("0x")
        .or_else(|| s.strip_prefix("0X"))
        .is_some_and(|h| !h.is_empty() && h.bytes().all(|b| b.is_ascii_hexdigit()))
}

/// The `sdkconfig.defaults` a build of `profile` uses.
pub fn defaults_text(m: &Manifest, profile: &str) -> String {
    sdkconfig_defaults(
        &m.effective_config(profile),
        !m.partitions.is_empty(),
        profile,
    )
}

fn sdkconfig_defaults(
    config: &BTreeMap<ConfigKey, ConfigValue>,
    custom_table: bool,
    profile: &str,
) -> String {
    let mut s = format!("# {HEADER} Profile: {profile}.\n");
    for (k, v) in config {
        s.push_str(&kconfig_line(k, v));
        s.push('\n');
    }
    if custom_table {
        // After [config], so the table in idf.toml always wins.
        s.push_str("CONFIG_PARTITION_TABLE_CUSTOM=y\n");
        s.push_str("CONFIG_PARTITION_TABLE_CUSTOM_FILENAME=\"partitions.csv\"\n");
    }
    s
}

fn partitions_csv(parts: &[Partition]) -> String {
    let mut s = format!("# {HEADER}\n# Name, Type, SubType, Offset, Size, Flags\n");
    for p in parts {
        let offset = p.offset.map(|o| format!("{:#x}", o.0)).unwrap_or_default();
        let flags: Vec<&str> = [(p.encrypted, "encrypted"), (p.readonly, "readonly")]
            .into_iter()
            .filter_map(|(on, f)| on.then_some(f))
            .collect();
        let _ = writeln!(
            s,
            "{}",
            format!(
                "{}, {}, {}, {offset}, {:#x}, {}",
                p.name.get_ref(),
                p.kind,
                p.subtype,
                p.size.0,
                flags.join(":")
            )
            .trim_end()
        );
    }
    s
}

/// Write `text` unless the file already holds exactly that. Returns whether
/// it wrote.
fn write_if_changed(path: &Path, text: &str) -> Result<bool> {
    if std::fs::read_to_string(path).is_ok_and(|old| old == text) {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        fsx::create_dir_all(parent)?;
    }
    fsx::write(path, text)?;
    Ok(true)
}

/// A configured build: the SDK it uses and where it lives.
pub struct Build<'a> {
    pub layout: Layout,
    pub installed: &'a Installed,
    env: Environment,
}

impl<'a> Build<'a> {
    pub fn new(layout: Layout, installed: &'a Installed) -> Build<'a> {
        let mut env = installed.environment();
        env.vars.extend([
            ("IDF_TARGET".to_owned(), layout.target.as_str().to_owned()),
            // The SDK has no .git (see P1); there are no submodules to check.
            ("IDF_SKIP_CHECK_SUBMODULES".to_owned(), "1".to_owned()),
            // The manager only runs when [dependencies] produced a manifest
            // (see deps.rs); without one it would only slow configure down.
            (
                "IDF_COMPONENT_MANAGER".to_owned(),
                if layout
                    .project_dir()
                    .join("main/idf_component.yml")
                    .is_file()
                {
                    "1"
                } else {
                    "0"
                }
                .to_owned(),
            ),
        ]);
        Build {
            layout,
            installed,
            env,
        }
    }

    pub fn env(&self) -> &Environment {
        &self.env
    }

    /// The same build with one more environment variable.
    pub fn with_var(mut self, key: &str, value: &str) -> Self {
        self.env.vars.push((key.to_owned(), value.to_owned()));
        self
    }

    /// The SDK's Python interpreter.
    pub fn python(&self) -> PathBuf {
        self.installed.python.python()
    }

    /// A command for a tool from the SDK (`cmake`, `ninja`, …), with the
    /// SDK's environment.
    pub fn tool(&self, name: &str) -> Result<Command> {
        let exe = self
            .env
            .path
            .iter()
            .map(|d| d.join(name))
            .find(|p| p.is_file())
            .ok_or_else(|| miette::miette!("{name} is not part of the installed SDK"))?;
        let mut cmd = Command::new(exe);
        self.env.apply(&mut cmd);
        Ok(cmd)
    }

    /// Run CMake's configure step if the build directory needs it; whether
    /// it ran.
    pub fn configure(&self, generated: &Generated) -> Result<bool> {
        let dir = self.layout.dir();
        if !generated.changed && dir.join("build.ninja").is_file() {
            return Ok(false);
        }
        ui::status(
            "Configuring",
            format!("{} for {}", self.layout.profile, self.layout.target),
        );
        let mut cmd = self.tool("cmake")?;
        cmd.arg("-G")
            .arg("Ninja")
            .arg("-S")
            .arg(self.layout.project_dir())
            .arg("-B")
            .arg(&dir)
            .arg(format!("-DIDF_TARGET={}", self.layout.target))
            .arg(format!(
                "-DPYTHON={}",
                self.installed.python.python().display()
            ))
            .arg("-DCCACHE_ENABLE=0");
        run_captured(cmd, "CMake configure")?;
        Ok(true)
    }

    /// Build everything (`ninja` via `cmake --build`).
    pub fn compile(&self) -> Result<()> {
        let mut cmd = self.tool("cmake")?;
        cmd.arg("--build").arg(self.layout.dir());
        let status = cmd
            .status()
            .into_diagnostic()
            .wrap_err("running cmake --build")?;
        if !status.success() {
            bail!("build failed");
        }
        Ok(())
    }

    /// Point `compile_commands.json` in the project root at this build, for
    /// clangd and friends. A real file there is left alone.
    pub fn link_compile_commands(&self) -> Result<()> {
        let link = self.layout.root.join("compile_commands.json");
        let target = self.layout.relative_dir().join("compile_commands.json");
        match std::fs::symlink_metadata(&link) {
            Ok(meta) if !meta.file_type().is_symlink() => return Ok(()),
            Ok(_) if std::fs::read_link(&link).is_ok_and(|t| t == target) => return Ok(()),
            Ok(_) => std::fs::remove_file(&link)
                .into_diagnostic()
                .wrap_err_with(|| format!("removing {}", link.display()))?,
            Err(_) => {}
        }
        symlink(&target, &link)
    }

    /// The application image, from IDF's project_description.json.
    pub fn app_bin(&self) -> Option<PathBuf> {
        let text =
            std::fs::read_to_string(self.layout.dir().join("project_description.json")).ok()?;
        let v: serde_json::Value = serde_json::from_str(&text).ok()?;
        Some(self.layout.dir().join(v.get("app_bin")?.as_str()?))
    }
}

#[cfg(unix)]
fn symlink(target: &Path, link: &Path) -> Result<()> {
    std::os::unix::fs::symlink(target, link)
        .into_diagnostic()
        .wrap_err_with(|| format!("linking {}", link.display()))
}

#[cfg(not(unix))]
fn symlink(_target: &Path, _link: &Path) -> Result<()> {
    Ok(())
}

/// Run a command, showing its output only with `-v` or when it fails.
pub fn run_captured(mut cmd: Command, what: &str) -> Result<()> {
    ui::detail("Running", format!("{cmd:?}"));
    if ui::verbosity() >= ui::Verbosity::Verbose {
        let status = cmd
            .status()
            .into_diagnostic()
            .wrap_err_with(|| format!("running {what}"))?;
        if !status.success() {
            bail!("{what} failed");
        }
        return Ok(());
    }
    let out = cmd
        .output()
        .into_diagnostic()
        .wrap_err_with(|| format!("running {what}"))?;
    if !out.status.success() {
        let mut log = String::from_utf8_lossy(&out.stdout).into_owned();
        log.push_str(&String::from_utf8_lossy(&out.stderr));
        bail!("{what} failed:\n{}", log.trim_end());
    }
    Ok(())
}

/// The manifest's target unless overridden on the command line.
pub fn target(manifest: &Manifest, cli: Option<&Chip>) -> Chip {
    cli.cloned()
        .unwrap_or_else(|| manifest.project.target.clone())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cmake_strings_never_need_escaping() {
        assert_eq!(cmake_str("/a b/c"), "[=[/a b/c]=]");
        assert_eq!(cmake_str("x]=]y"), "[==[x]=]y]==]");
    }

    #[test]
    fn generated_cmakelists() {
        let top = top_cmakelists(
            "blink",
            Path::new("/p/build/esp32/dev/sdkconfig"),
            Some(Path::new("/p/components")),
        );
        insta::assert_snapshot!(top);
        let main = main_cmakelists(
            &[
                PathBuf::from("/p/src/main.c"),
                PathBuf::from("/p/src/x/y.cpp"),
            ],
            Path::new("/p/src"),
        );
        insta::assert_snapshot!(main);
    }

    #[test]
    fn defaults_and_partitions() {
        let m = Manifest::parse(
            r#"
[project]
name = "blink"
target = "esp32s3"
idf = "6.0"

[config]
FREERTOS_HZ = 1000
LOG_COLORS = false
APP_NAME = "say \"hi\""
BOOTLOADER_OFFSET = "0x1000"

[[partition]]
name = "nvs"
type = "data"
subtype = "nvs"
size = "24K"

[[partition]]
name = "factory"
type = "app"
subtype = "factory"
offset = "64K"
size = "1M"
readonly = true

[profile.release.config]
FREERTOS_HZ = 100
"#,
            "idf.toml",
        )
        .unwrap();
        insta::assert_snapshot!(sdkconfig_defaults(
            &m.effective_config("release"),
            true,
            "release"
        ));
        insta::assert_snapshot!(partitions_csv(&m.partitions));
    }

    #[test]
    fn finds_sources_recursively() {
        let dir = tempfile::tempdir().unwrap();
        let src = dir.path().join("src");
        for f in [
            "main.c",
            "net/wifi.cpp",
            "README.md",
            ".hidden/x.c",
            "asm/start.S",
        ] {
            let p = src.join(f);
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(p, "").unwrap();
        }
        let found: Vec<_> = sources(&src)
            .unwrap()
            .into_iter()
            .map(|p| p.strip_prefix(&src).unwrap().to_string_lossy().into_owned())
            .collect();
        assert_eq!(found, ["asm/start.S", "main.c", "net/wifi.cpp"]);
        assert!(sources(&dir.path().join("missing")).unwrap().is_empty());
    }

    #[test]
    fn kconfig_stub_sources_the_real_file() {
        assert_eq!(
            kconfig_stub(Path::new("/p/src/Kconfig.projbuild")),
            format!("# {HEADER}\nsource \"/p/src/Kconfig.projbuild\"\n")
        );
    }

    #[test]
    fn rewrites_only_on_change() {
        let dir = tempfile::tempdir().unwrap();
        let f = dir.path().join("a/b.txt");
        assert!(write_if_changed(&f, "x").unwrap());
        assert!(!write_if_changed(&f, "x").unwrap());
        assert!(write_if_changed(&f, "y").unwrap());
    }
}
